"""Episode lengths of the final evaluation (128 episodes) for chosen p3main cells (writer request R17, 2026-11-25).

usage: python scripts/focus/eplen.py

Reads eval_scores/episode_lengths of each run's results/scores.json (supervisor results folder; fetch the file of an
archived run first with download_run(run_id, paths=['results/scores.json'])), caches the per-run numbers in
results/data/eplen_p3main.tsv (so the paper can be rebuilt after the local copies are released) and writes
results/tables/eplen_values.tex and eplen.md.

Macros, per cell (all reported seeds): \\fv{eplen:<task>:<arm>:<field>} with field
  mean   mean length over all episodes of all seeds (steps)
  full   share of full-length episodes (length = the task's 1000 steps), in percent, integer
  lo, hi smallest and largest per-seed mean length
  n      number of seeds
and per seed: \\fv{eplen:<task>:<arm>:<seed>:<mean|full>} with full = number of full-length episodes out of 128.
"""
import csv
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import table  # noqa: E402

FULL = 1000  # episode length of every DFlex task here (Hopper, Ant, Humanoid, SNU Humanoid, HalfCheetah)
CELLS = [(t, 'f_ab_rew_neg') for t in ('hopper', 'ant', 'humanoid', 'snu_humanoid')] + [
    ('ant', 'f_main_ot'), ('cheetah', 'f_main_ot'), ('humanoid', 'f_ab_demos1')]
CACHE = os.path.join(table.DATA, 'eplen_p3main.tsv')
COLS = ['run_id', 'task', 'arm', 'seed', 'episodes', 'mean_len', 'full']


def main():
    cache = {}
    if os.path.exists(CACHE):
        cache = {r['run_id']: r for r in csv.DictReader(open(CACHE), delimiter='\t')}
    rows = [r for r in csv.DictReader(open(os.path.join(table.DATA, 'manifest.tsv')), delimiter='\t')
            if r['batch'] == 'p3main' and (r['task'], r['arm']) in CELLS]
    latest = {}
    for r in rows:  # the latest row of a (cell, seed) is the run that counts
        latest[(r['task'], r['arm'], r['seed'])] = r
    missing = []
    for (t, a, s), r in latest.items():
        p = os.path.join(table.RESULTS_DIR, r['run_id'], 'results', 'scores.json')
        if os.path.exists(p):
            L = np.array(json.load(open(p))['eval_scores/episode_lengths'], float)
            cache[r['run_id']] = dict(run_id=r['run_id'], task=t, arm=a, seed=s, episodes=len(L),
                                      mean_len=f'{L.mean():.1f}', full=int((L >= FULL).sum()))
        elif r['run_id'] not in cache:
            missing.append(r['run_id'])
    if missing:
        sys.exit(f'{len(missing)} runs without scores.json or cache entry: ' + ' '.join(missing))
    with open(CACHE, 'w') as f:
        f.write('\t'.join(COLS) + '\n')
        for r in sorted(cache.values(), key=lambda r: (r['task'], r['arm'], int(r['seed']))):
            f.write('\t'.join(str(r[c]) for c in COLS) + '\n')

    vals, md = {}, ['Episode lengths in the final evaluation (128 episodes per seed), p3main. Generated by '
                    'scripts/focus/eplen.py.', '',
                    '| Task | Arm | seeds | mean length | per-seed mean [min, max] | full-length episodes |',
                    '|:-|:-|-:|-:|-:|-:|']
    for t, a in CELLS:
        runs = [cache[r['run_id']] for (tt, aa, _), r in sorted(latest.items(), key=lambda x: int(x[0][2]))
                if (tt, aa) == (t, a)]
        if not runs:
            continue
        m = np.array([float(r['mean_len']) for r in runs])
        eps = np.array([int(r['episodes']) for r in runs])
        full = np.array([int(r['full']) for r in runs])
        key = f'eplen:{t}:{a}'
        cell = dict(mean=f'{(m * eps).sum() / eps.sum():.0f}', full=f'{100 * full.sum() / eps.sum():.0f}',
                    lo=f'{m.min():.0f}', hi=f'{m.max():.0f}', n=str(len(runs)))
        for k, v in cell.items():
            vals[f'{key}:{k}'] = v
        for r in runs:
            vals[f'{key}:{r["seed"]}:mean'] = f'{float(r["mean_len"]):.0f}'
            vals[f'{key}:{r["seed"]}:full'] = str(r['full'])
        md.append(f'| {table.TASK_NAMES.get(t, t)} | {a} | {len(runs)} | {cell["mean"]} | [{cell["lo"]}, {cell["hi"]}] '
                  f'| {cell["full"]} % |')
    md += ['', 'Per seed (mean length; full-length episodes of 128):', '']
    for t, a in CELLS:
        per = [(k.split(':')[3], v) for k, v in vals.items() if k.startswith(f'eplen:{t}:{a}:') and k.endswith(':mean')
               and k.count(':') == 4]
        if per:
            md.append(f'- {table.TASK_NAMES.get(t, t)} {a}: ' + ', '.join(
                f'{s}: {v} ({vals[f"eplen:{t}:{a}:{s}:full"]})' for s, v in per))
    with open(os.path.join(table.TABLES, 'eplen.md'), 'w') as f:
        f.write('\n'.join(md) + '\n')
    with open(os.path.join(table.TABLES, 'eplen_values.tex'), 'w') as f:
        f.write('% generated by scripts/focus/eplen.py; one definition per number\n')
        f.write('\\providecommand{\\fv}[1]{\\csname fv@#1\\endcsname}\n')
        for k, v in vals.items():
            f.write(f'\\expandafter\\def\\csname fv@{k}\\endcsname{{{v}}}\n')
    print(f'{len(vals)} macros; cache {CACHE}')


if __name__ == '__main__':
    main()
