"""Generate TUTOR task files (no task file is edited by hand).

Base: the frozen MENTOR configuration of the task (tasks/mentor/icml/dflex_<task>.yaml), agent TUTOR/DFlex, with
Stage I by Levenberg-Marquardt and forward differences (scripts/tutor/overrides.py: GF_STAGE1), the shared evaluation
protocol (dedicated env, 128 episodes, an evaluation at every round end), every setting in the body (the sweep block
holds the seeds only). An arm is a named set of changes under agent.mentor (ARMS).

Writes tasks/tutor/gf/<batch>/<task>_<arm>_s<seed>.yaml, one file per seed (the spawner runs a file's seed, it does
not expand a sweep block).
usage: python scripts/tutor/make_task_files.py <batch> <task>:<arm>:<seed,seed,...> [...]
"""

import copy
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.abspath(os.path.join(HERE, '../..'))
sys.path.insert(0, HERE)
from overrides import GF_STAGE1  # noqa: E402

OUT = 'tasks/tutor/gf'
LM = {'teacher.kind': 'lmplan', 'teacher.lm_jacobian': 'broyden', 'teacher.iters': 20}
ARMS = {
    'ref': {},  # MENTOR's gradient teacher (reference row; Stage I without gradients as every arm)
    'lmbr20': LM,
    'lmmodel_every': {'teacher.kind': 'lmmodel', 'teacher.lm_model_jac': 'every', 'teacher.iters': 10},
    'lmmodel_every20': {'teacher.kind': 'lmmodel', 'teacher.lm_model_jac': 'every', 'teacher.iters': 20},
    'lmmodel_br': {'teacher.kind': 'lmmodel', 'teacher.lm_model_jac': 'broyden', 'teacher.iters': 20},
    'hsfwd': {'teacher.kind': 'hindsight', 'teacher.hs_form': 'forward', 'teacher.sample_n': 64,
              'teacher.sample_noise': 0.1},
}


def _set(d, dotted, value):
    keys = dotted.split('.')
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    d[keys[-1]] = value


def task_file(batch, task, arm, seeds):
    base = yaml.safe_load(open(os.path.join(CODE, f'tasks/mentor/icml/dflex_{task}.yaml')))
    mentor = copy.deepcopy(base['agent']['mentor'])
    for k, v in {**GF_STAGE1.get(task, GF_STAGE1['default']), **ARMS[arm]}.items():
        _set(mentor, k, v)
    return dict(
        task=dict(name='DFlex', env=dict(env_name=task)),
        agent=dict(name='TUTOR/DFlex', ckpt_every=-1, protocol_eval=True, eval_every_steps=1, mentor=mentor),
        logdir=f'workdir/tutor-{batch}-{task}-{arm}/$(date +%Y%m%d-%H%M%S.%2N)',
        wandb=dict(mode='offline'),
        run='train_eval',
        seed=seeds[0],
        spawner=dict(runtime='12h'),
    )


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    batch, cells = sys.argv[1], sys.argv[2:]
    out = os.path.join(CODE, OUT, batch)
    os.makedirs(out, exist_ok=True)
    for cell in cells:
        task, arm, seeds = cell.split(':')
        for seed in [int(s) for s in seeds.split(',')]:
            body = task_file(batch, task, arm, [seed])
            hdr = (f'# Generated by scripts/tutor/make_task_files.py ({batch}, arm {arm}, seed {seed}); do not edit.\n'
                   f'# Base: tasks/mentor/icml/dflex_{task}.yaml; Stage I without gradients; changes: {ARMS[arm] or "none"}\n')
            path = os.path.join(out, f'{task}_{arm}_s{seed}.yaml')
            with open(path, 'w') as f:
                f.write(hdr + yaml.safe_dump(body, sort_keys=False, default_flow_style=None))
            print(path)


if __name__ == '__main__':
    main()
